#!/usr/bin/env python3
"""Tables and numbers for the extended studies (results/ext_*.jsonl) -> results/tex/ext_*_{en,ru}.tex
and results/extended.json."""
import json, os
from collections import defaultdict
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results"); TEX = os.path.join(RES, "tex")
NAME = {"en": {"proposed": "Proposed", "abl_no_detect": "CBF only (no detection)",
               "B1_consensus": r"Consensus~\cite{ren2008distributed}", "B2_wmsr": r"W-MSR~\cite{leblanc2013resilient,dibaji2017resilient}",
               "B3_consensus_cbf": r"Consensus + CBF~\cite{wang2017safety}"},
        "ru": {"proposed": "Предложенный", "abl_no_detect": "Только CBF (без обнаружения)",
               "B1_consensus": r"Консенсус~\cite{ren2008distributed}", "B2_wmsr": r"W-MSR~\cite{leblanc2013resilient,dibaji2017resilient}",
               "B3_consensus_cbf": r"Консенсус + CBF~\cite{wang2017safety}"}}
M5 = ["proposed", "abl_no_detect", "B1_consensus", "B2_wmsr", "B3_consensus_cbf"]


def load(study):
    fn = os.path.join(RES, f"ext_{study}.jsonl")
    return [json.loads(l) for l in open(fn)] if os.path.exists(fn) else []


def ci(x, B=2000):
    x = np.asarray(x, float); rng = np.random.default_rng(0)
    m = rng.choice(x, (B, len(x))).mean(1)
    return x.mean(), np.percentile(m, 2.5), np.percentile(m, 97.5)


def cell(rs):
    if not rs:
        return "--", 0, float("nan")
    m, lo, hi = ci([r["peak_Emax"] for r in rs])
    return f"{m:.2f} [{lo:.2f}, {hi:.2f}]", sum(r["collision"] for r in rs), min(r["d_min"] for r in rs)


def det_stats(rs):
    ev = [e for r in rs for e in r["events"]]
    out = {}
    for ch in sorted({e[0] for e in ev}):
        xs = [e for e in ev if e[0] == ch]
        dl = [e[2] for e in xs if e[1] and e[2] is not None]
        out[ch] = dict(n=len(xs), rate=float(np.mean([e[1] for e in xs])),
                       median_delay=float(np.median(dl)) if dl else None)
    return out


def table(caption, label, header, rows):
    L = [r"\begin{table}[t]", r"\centering", r"\caption{" + caption + r"}\label{" + label + "}", r"\footnotesize",
         r"\resizebox{\linewidth}{!}{%", r"\begin{tabular}{l" + "c" * (len(header) - 1) + "}", r"\toprule",
         " & ".join(header) + r" \\", r"\midrule"] + [" & ".join(map(str, r)) + r" \\" for r in rows] + \
        [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
    return "% AUTO-GENERATED by scripts/make_extended.py\n" + "\n".join(L) + "\n"


def main():
    os.makedirs(TEX, exist_ok=True)
    X = {}
    # ---------------- nonlinear quadrotor
    q = load("quad")
    if q:
        by = defaultdict(list)
        for r in q:
            by[(r["method"], r["scenario"])].append(r)
        X["quad"] = {"n_runs": len(q), "runs_per_cell": len(by[("proposed", "hybrid")]),
                     "fa_clean_proposed": sum(r["false_alarms"] for r in by[("proposed", "clean")]),
                     "viol_proposed": sum(r["collision"] for m in ["proposed"] for s in ("sensor", "hybrid") for r in by[(m, s)]),
                     "viol": {m: {s: sum(r["collision"] for r in by[(m, s)]) for s in ("sensor", "hybrid")} for m in M5},
                     "dmin_worst": {m: min(r["d_min"] for s in ("clean", "sensor", "hybrid") for r in by[(m, s)]) for m in M5},
                     "peak": {m: {s: float(np.mean([r["peak_Emax"] for r in by[(m, s)]])) for s in ("clean", "sensor", "hybrid")} for m in M5},
                     "tilt_max": float(max(r["tilt_max_deg"] for r in q)),
                     "tilt_max_proposed": float(max(r["tilt_max_deg"] for r in q if r["method"] == "proposed")),
                     "infeasible": int(sum(r["qp_infeasible_steps"] > 0 for r in q if r["method"] == "proposed")),
                     "detection": det_stats([r for r in q if r["method"] == "proposed"])}
        for lang in ("en", "ru"):
            hdr = (["Method", "No attack", "Sensor", "Time-staggered", "Worst $d_{\\min}$, m"] if lang == "en" else
                   ["Метод", "Без атаки", "Сенсорная", "Разнесённая", "Худшее $d_{\\min}$, м"])
            rows = []
            for m in M5:
                c0, _, _ = cell(by[(m, "clean")]); c1, v1, _ = cell(by[(m, "sensor")]); c2, v2, _ = cell(by[(m, "hybrid")])
                rows.append([NAME[lang][m], c0, f"{c1} ({v1})", f"{c2} ({v2})", f"{X['quad']['dmin_worst'][m]:.2f}"])
            n = X["quad"]["runs_per_cell"]
            cap = (f"Nonlinear quadrotor model: peak worst-follower error $E_{{\\max}}$ (m), mean [95\\% CI] over {n} runs, and runs with $d_{{\\min}}<d_s$ (in parentheses)."
                   if lang == "en" else
                   f"Нелинейная модель квадрокоптера: пиковая ошибка худшего ведомого $E_{{\\max}}$ (м), среднее [95\\% ДИ] по {n} прогонам, и число прогонов с $d_{{\\min}}<d_s$ (в скобках).")
            open(os.path.join(TEX, f"ext_quad_{lang}.tex"), "w").write(table(cap, "tab:quad", hdr, rows))
    # ---------------- stealthy attacks
    st = load("stealth")
    if st:
        by = defaultdict(list)
        for r in st:
            by[(r["method"], r["scenario"])].append(r)
        X["stealth"] = {"runs_per_cell": len(by[("proposed", "stealth_ramp")]),
                        "viol": {m: {s: sum(r["collision"] for r in by[(m, s)]) for s in ("stealth_ramp", "stealth_sub")} for m in M5},
                        "peak": {m: {s: float(np.mean([r["peak_Emax"] for r in by[(m, s)]])) for s in ("stealth_ramp", "stealth_sub")} for m in M5},
                        "det_ramp": det_stats(by[("proposed", "stealth_ramp")]),
                        "det_sub": det_stats(by[("proposed", "stealth_sub")])}
        for lang in ("en", "ru"):
            hdr = (["Method", "Slow spoofing ramp", "Sub-threshold FDI + actuation"] if lang == "en" else
                   ["Метод", "Медленная подмена", "Подпороговые ложные данные + исполн."])
            rows = []
            for m in M5:
                c1, v1, _ = cell(by[(m, "stealth_ramp")]); c2, v2, _ = cell(by[(m, "stealth_sub")])
                rows.append([NAME[lang][m], f"{c1} ({v1})", f"{c2} ({v2})"])
            n = X["stealth"]["runs_per_cell"]
            cap = (f"Stealthy attacks: peak worst-follower error $E_{{\\max}}$ (m), mean [95\\% CI] over {n} runs, and runs with $d_{{\\min}}<d_s$ (in parentheses)."
                   if lang == "en" else
                   f"Скрытные атаки: пиковая ошибка худшего ведомого $E_{{\\max}}$ (м), среднее [95\\% ДИ] по {n} прогонам, и число прогонов с $d_{{\\min}}<d_s$ (в скобках).")
            open(os.path.join(TEX, f"ext_stealth_{lang}.tex"), "w").write(table(cap, "tab:stealth", hdr, rows))
    # ---------------- scalability
    sc = load("scale")
    main_rows = [json.loads(l) for l in open(os.path.join(RES, "mc_results.jsonl"))]
    if sc:
        by = defaultdict(list)
        for r in sc:
            by[(r["method"], r["n"])].append(r)
        for r in main_rows:
            if r["scenario"] == "hybrid":
                by[(r["method"], 6)].append(r)
        Ms = ["proposed", "B1_consensus", "B2_wmsr", "B3_consensus_cbf"]
        X["scale"] = {"runs_per_cell": len(by[("proposed", 20)]),
                      "viol": {m: {str(n): sum(r["collision"] for r in by[(m, n)]) for n in (6, 10, 20)} for m in Ms},
                      "peak": {m: {str(n): float(np.mean([r["peak_Emax"] for r in by[(m, n)]])) for n in (6, 10, 20)} for m in Ms},
                      "fa": {str(n): sum(r["false_alarms"] for r in by[("proposed", n)]) for n in (6, 10, 20)}}
        for lang in ("en", "ru"):
            hdr = (["Method", "6 followers", "10 followers", "20 followers"] if lang == "en" else ["Метод", "6 ведомых", "10 ведомых", "20 ведомых"])
            rows = []
            for m in Ms:
                cells = []
                for n in (6, 10, 20):
                    c, v, _ = cell(by[(m, n)]); cells.append(f"{c} ({v}/{len(by[(m, n)])})")
                rows.append([NAME[lang][m]] + cells)
            cap = ("Scalability under time-staggered attacks: peak worst-follower error $E_{\\max}$ (m), mean [95\\% CI], and runs with $d_{\\min}<d_s$."
                   if lang == "en" else
                   "Масштабируемость при разнесённых атаках: пиковая ошибка худшего ведомого $E_{\\max}$ (м), среднее [95\\% ДИ], и число прогонов с $d_{\\min}<d_s$.")
            open(os.path.join(TEX, f"ext_scale_{lang}.tex"), "w").write(table(cap, "tab:scale", hdr, rows))
    # ---------------- sensitivity
    se = load("sens")
    if se:
        thr = defaultdict(list); amp = defaultdict(list)
        for r in se:
            if "theta_c" in r:
                thr[(r["theta_c"], r["theta_u"], r["scenario"])].append(r)
            if "attack_scale" in r:
                amp[(r["method"], r["attack_scale"])].append(r)
        tcs, tus = sorted({k[0] for k in thr}), sorted({k[1] for k in thr})
        X["sens"] = {"thresholds": {f"{tc}/{tu}": {
            "fa_clean": int(sum(r["false_alarms"] for r in thr[(tc, tu, "clean")])),
            "peak_hybrid": float(np.mean([r["peak_Emax"] for r in thr[(tc, tu, "hybrid")]])),
            "viol_hybrid": int(sum(r["collision"] for r in thr[(tc, tu, "hybrid")])),
            "det": det_stats(thr[(tc, tu, "hybrid")])} for tc in tcs for tu in tus},
            "amplitude": {f"{m}/{s}": {"peak": float(np.mean([r["peak_Emax"] for r in amp[(m, s)]])),
                                       "viol": int(sum(r["collision"] for r in amp[(m, s)])), "n": len(amp[(m, s)]),
                                       "det": det_stats(amp[(m, s)]) if m == "proposed" else None}
                          for (m, s) in sorted(amp)},
            "runs_per_cell": len(thr[(0.5, 0.4, "hybrid")])}
        for lang in ("en", "ru"):
            en = lang == "en"
            hdr = (["$\\theta_c$, m", "$\\theta_u$, m/s$^2$", "Peak $E_{\\max}$, m", "$d_{\\min}<d_s$", "False alarms", "Actuation delay, s"] if en else
                   ["$\\theta_c$, м", "$\\theta_u$, м/с$^2$", "Пик $E_{\\max}$, м", "$d_{\\min}<d_s$", "Ложные тревоги", "Задержка исполн., с"])
            rows = []
            for tc in tcs:
                for tu in tus:
                    d = X["sens"]["thresholds"][f"{tc}/{tu}"]; rs = thr[(tc, tu, "hybrid")]
                    c, v, _ = cell(rs)
                    rows.append([f"{tc}", f"{tu}", c, v, d["fa_clean"], f"{d['det']['actuator']['median_delay']:.2f}"])
            n = X["sens"]["runs_per_cell"]
            cap = (f"Sensitivity to the detection thresholds ({n} time-staggered and {n} attack-free runs per row): peak worst-follower error, mean [95\\% CI]; runs with $d_{{\\min}}<d_s$; false alarms in the attack-free runs; median actuation detection delay."
                   if en else
                   f"Чувствительность к порогам обнаружения ({n} прогонов с разнесёнными атаками и {n} без атак на строку): пиковая ошибка худшего ведомого, среднее [95\\% ДИ]; прогоны с $d_{{\\min}}<d_s$; ложные тревоги в прогонах без атак; медианная задержка обнаружения исполнительной атаки.")
            open(os.path.join(TEX, f"ext_sens_{lang}.tex"), "w").write(table(cap, "tab:sens", hdr, rows))
            hdr = (["Amplitude scale", "Proposed", "Consensus~\\cite{ren2008distributed}"] if en else
                   ["Коэффициент амплитуды", "Предложенный", "Консенсус~\\cite{ren2008distributed}"])
            rows = []
            for sc_ in sorted({k[1] for k in amp}):
                c1, v1, _ = cell(amp[("proposed", sc_)]); c2, v2, _ = cell(amp[("B1_consensus", sc_)])
                rows.append([f"{sc_}", f"{c1} ({v1})", f"{c2} ({v2})"])
            cap = (f"Time-staggered attacks with scaled sensing and false-data amplitudes ({n} runs per cell): peak worst-follower error $E_{{\\max}}$ (m), mean [95\\% CI], and runs with $d_{{\\min}}<d_s$ (in parentheses)."
                   if en else
                   f"Разнесённые атаки с масштабированной амплитудой сенсорной подмены и ложных данных ({n} прогонов на ячейку): пиковая ошибка худшего ведомого $E_{{\\max}}$ (м), среднее [95\\% ДИ], и число прогонов с $d_{{\\min}}<d_s$ (в скобках).")
            open(os.path.join(TEX, f"ext_amp_{lang}.tex"), "w").write(table(cap, "tab:amp", hdr, rows))
    json.dump(X, open(os.path.join(RES, "extended.json"), "w"), indent=1)
    print(json.dumps(X, indent=1)[:4000])


if __name__ == "__main__":
    main()
